import fs from "node:fs";
import path from "node:path";

import type { Address } from "viem";

import { CONTRACTS_DIR, REPO_ROOT } from "./context.ts";

export interface DeploymentRecord {
  network: string;
  chainId: number;
  issuerRegistry: Address;
  siteCredentialManager: Address;
  deploymentBlock: number;
  deployer: Address;
  registryAdmin: Address;
  deployedAt: string;
}

const DEPLOYMENTS_DIR = path.join(CONTRACTS_DIR, "deployments");
/** Addresses consumed by the web app, keyed by chain id. */
export const WEB_DEPLOYMENTS_FILE = path.join(REPO_ROOT, "apps/web/src/config/deployments.json");

/**
 * Demo fixtures consumed by the web app in demo mode (personas, seeded
 * credentials and their sample certificates), keyed by chain id. Git-ignored:
 * regenerated by every seed.
 */
export const WEB_DEMO_SEED_FILE = path.join(REPO_ROOT, "apps/web/src/config/demo-seed.json");

function readJson<T>(file: string, fallback: T): T {
  try {
    return JSON.parse(fs.readFileSync(file, "utf8")) as T;
  } catch {
    return fallback;
  }
}

function writeJson(file: string, value: unknown): void {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`);
}

export function deploymentFile(networkName: string): string {
  return path.join(DEPLOYMENTS_DIR, `${networkName}.json`);
}

export function readDeployment(networkName: string): DeploymentRecord {
  const file = deploymentFile(networkName);
  const record = readJson<DeploymentRecord | undefined>(file, undefined);
  if (!record) {
    throw new Error(`No deployment found for "${networkName}" (${file}). Run the deploy script first.`);
  }
  return record;
}

export function saveDeployment(record: DeploymentRecord): void {
  writeJson(deploymentFile(record.network), record);

  const web = readJson<Record<string, DeploymentRecord>>(WEB_DEPLOYMENTS_FILE, {});
  web[String(record.chainId)] = record;
  writeJson(WEB_DEPLOYMENTS_FILE, web);
}

export function updateDeploymentAdmin(networkName: string, registryAdmin: Address): void {
  const record = readDeployment(networkName);
  saveDeployment({ ...record, registryAdmin });
}

/** Merges one network's demo fixtures into the web app's demo seed file. */
export function saveWebDemoSeed(chainId: number, value: unknown): void {
  const web = readJson<Record<string, unknown>>(WEB_DEMO_SEED_FILE, {});
  web[String(chainId)] = value;
  writeJson(WEB_DEMO_SEED_FILE, web);
}
