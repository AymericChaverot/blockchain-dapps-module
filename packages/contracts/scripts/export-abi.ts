/**
 * Copies the compiled ABIs into the web app as typed `as const` exports so
 * that wagmi/viem calls are fully type-checked.
 *
 *   pnpm export:abi   (also run automatically by the deploy script)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const CONTRACTS_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.resolve(CONTRACTS_DIR, "../../apps/web/src/config/abis.ts");
const CONTRACTS = ["IssuerRegistry", "SiteCredentialManager"] as const;

export function exportAbis(): void {
  const sections = CONTRACTS.map((name) => {
    const artifactPath = path.join(CONTRACTS_DIR, "artifacts/contracts", `${name}.sol`, `${name}.json`);
    if (!fs.existsSync(artifactPath)) {
      throw new Error(`Artifact not found: ${artifactPath}. Run "pnpm compile" first.`);
    }
    const { abi } = JSON.parse(fs.readFileSync(artifactPath, "utf8")) as { abi: unknown };
    const exportName = `${name.charAt(0).toLowerCase()}${name.slice(1)}Abi`;
    return `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  });

  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(
    OUTPUT,
    `// AUTO-GENERATED by packages/contracts/scripts/export-abi.ts. Do not edit by hand.\n\n${sections.join("\n")}`,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  exportAbis();
  console.log(`ABIs written to ${OUTPUT}`);
}
